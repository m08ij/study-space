/* ========== دوال البحث ========== */
function findCourseByCode(code){
  code = String(code || '').trim();
  if(!code) return null;
  var normalized = code.replace(/^0+/, '');
  if(!normalized) return null;

  // 1) مطابقة مباشرة
  if(COURSE_BY_CODE[code] && COURSE_BY_CODE[code].length){
    var name = COURSE_BY_CODE[code][0];
    return {name: name, info: COURSES_DB[name]};
  }

  // 2) مطابقة بدون أصفار + aliases
  var keys = Object.keys(COURSES_DB);
  for(var i = 0; i < keys.length; i++){
    var info = COURSES_DB[keys[i]];
    if(info.code.replace(/^0+/, '') === normalized){
      return {name: keys[i], info: info};
    }
    // ✅ افحص الـ aliases
    if(info.aliases && info.aliases.length){
      for(var a = 0; a < info.aliases.length; a++){
        if(String(info.aliases[a]).replace(/^0+/, '') === normalized){
          return {name: keys[i], info: info};
        }
      }
    }
  }
  return null;
}

function searchCourses(query){
  query = String(query || '').trim().toLowerCase();
  if(!query) return [];
  var results = [];
  Object.keys(COURSES_DB).forEach(function(name){
    var info = COURSES_DB[name];
    if(name.toLowerCase().indexOf(query) > -1 || info.code.indexOf(query) > -1){
      results.push({name: name, info: info});
    }
  });
  return results;
}

/* ========== كشف التعارضات ========== */
function validateCoursesDB(){
  var issues = [];
  Object.keys(COURSE_BY_CODE).forEach(function(code){
    if(COURSE_BY_CODE[code].length > 1){
      issues.push('⚠️ كود مكرر: ' + code + ' → ' + COURSE_BY_CODE[code].join(' | '));
    }
  });
  Object.keys(COURSES_DB).forEach(function(name){
    (COURSES_DB[name].pre || []).forEach(function(p){
      if(!COURSES_DB[p]) issues.push('🔗 متطلب مفقود في "' + name + '": ' + p);
    });
  });
  var totals = { "uni-c":0, "uni-e":0, "faculty":0, "major-c":0, "major-e":0 };
  Object.keys(COURSES_DB).forEach(function(name){
    if(totals[COURSES_DB[name].t] !== undefined) totals[COURSES_DB[name].t] += COURSES_DB[name].h;
  });
  var expected = { "uni-c":18, "uni-e":6, "faculty":33, "major-c":88, "major-e":15 };
  Object.keys(expected).forEach(function(k){
    if(totals[k] !== expected[k]){
      issues.push('📊 ساعات ' + COURSE_TYPES[k].label + ': ' + totals[k] + ' (المتوقع ' + expected[k] + ')');
    }
  });
  if(issues.length === 0) console.log('✅ COURSES_DB صالح 100% — لا تعارضات');
  else {
    console.warn('⚠️ COURSES_DB فيه ' + issues.length + ' مشكلة:');
    issues.forEach(function(i){ console.warn('  ' + i); });
  }
  return issues;
}

